const _monCache = {};
function _inPoly(pts, x, y) {
  let ins = false;
  for (let i = 0, j = pts.length - 2; i < pts.length; j = i, i += 2) {
    const xi = pts[i], yi = pts[i + 1], xj = pts[j], yj = pts[j + 1];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) ins = !ins;
  }
  return ins;
}
function _starPts(cx, cy, ro, ri, n) {
  const p = [];
  for (let k = 0; k < n * 2; k++) {
    const r = k % 2 ? ri : ro, a = -Math.PI / 2 + k * Math.PI / n;
    p.push(cx + Math.cos(a) * r, cy + Math.sin(a) * r);
  }
  return p;
}

// 畫出 40x40 的像素資料（RGBA 陣列）
function rasterMon(art) {
  const W = 40, pal = art.pal;
  const col = (c) => hexRgb(c[0] === '#' ? c : pal[c]);
  const shapes = [], over = [];
  for (const s of art.s) {
    if (['e', 'p', 'r', 'star'].includes(s[0])) shapes.push(s); else over.push(s);
  }
  const owner = new Int16Array(W * W).fill(-1);
  const rgb = new Array(W * W).fill(null);
  shapes.forEach((s, i) => {
    let pts = null;
    if (s[0] === 'p') pts = s[1];
    if (s[0] === 'star') pts = _starPts(s[1], s[2], s[3], s[4], s[5]);
    const c = col(s[0] === 'p' ? s[2] : s[0] === 'star' ? s[6] : s[5]);
    for (let y = 0; y < W; y++) for (let x = 0; x < W; x++) {
      const px = x + .5, py = y + .5;
      let inside = false, k = 1;
      if (s[0] === 'e') {
        const nx = (px - s[1]) / s[3], ny = (py - s[2]) / s[4];
        inside = nx * nx + ny * ny <= 1;
        if (inside) {
          if (nx * .55 + ny * .83 > .6) k = .8;
          else if ((nx + .4) * (nx + .4) + (ny + .5) * (ny + .5) < .07) k = 1.18;
        }
      } else if (s[0] === 'r') {
        inside = px >= s[1] && px < s[1] + s[3] && py >= s[2] && py < s[2] + s[4];
        if (inside && py >= s[2] + s[4] - 1.5 && s[4] > 3) k = .82;
      } else inside = _inPoly(pts, px, py);
      if (inside) { owner[y * W + x] = i; rgb[y * W + x] = k === 1 ? c : shadeRgb(c, k); }
    }
  });
  const out = new Uint8ClampedArray(W * W * 4);
  const keyOf = (i) => { const s = shapes[i]; return s[0] === 'p' ? s[2] : s[0] === 'star' ? s[6] : s[5]; };
  for (let y = 0; y < W; y++) for (let x = 0; x < W; x++) {
    const i = y * W + x, o = owner[i];
    let c = rgb[i];
    if (o < 0) {
      // 外框
      const nb = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => {
        const xx = x + dx, yy = y + dy;
        return xx >= 0 && yy >= 0 && xx < W && yy < W && owner[yy * W + xx] >= 0;
      });
      if (!nb) continue;
      c = OUTLINE;
    } else {
      // 被前面的形狀蓋住的邊緣畫深一點，分出輪廓
      const edge = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => {
        const xx = x + dx, yy = y + dy;
        if (xx < 0 || yy < 0 || xx >= W || yy >= W) return false;
        const o2 = owner[yy * W + xx];
        return o2 > o && keyOf(o2) !== keyOf(o);
      });
      if (edge) c = shadeRgb(c, .62);
    }
    out[i * 4] = c[0]; out[i * 4 + 1] = c[1]; out[i * 4 + 2] = c[2]; out[i * 4 + 3] = 255;
  }
  const put = (x, y, c) => {
    if (x < 0 || y < 0 || x >= W || y >= W) return;
    const v = hexRgb(c[0] === '#' ? c : pal[c]), i = (y * W + x) * 4;
    out[i] = v[0]; out[i + 1] = v[1]; out[i + 2] = v[2]; out[i + 3] = 255;
  };
  const line = (x0, y0, x1, y1, c, clip) => {
    const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0), 1);
    for (let k = 0; k <= n; k++) {
      const x = Math.round(x0 + (x1 - x0) * k / n), y = Math.round(y0 + (y1 - y0) * k / n);
      if (clip && (x < 0 || y < 0 || x >= W || y >= W || owner[y * W + x] < 0)) continue;
      put(x, y, c);
    }
  };
  for (const s of over) {
    const [op, x, y] = s;
    if (op === 'eye') { put(x, y, '#ffffff'); put(x + 1, y, '#202028'); put(x, y + 1, '#202028'); put(x + 1, y + 1, '#202028'); put(x, y + 2, '#202028'); put(x + 1, y + 2, '#202028'); }
    else if (op === 'eyeL') { for (let a = 0; a < 3; a++) for (let b = 0; b < 3; b++) put(x + a, y + b, '#202028'); put(x, y, '#ffffff'); }
    else if (op === 'dot') { put(x, y, '#202028'); put(x, y + 1, '#202028'); }
    else if (op === 'smile') { put(x, y, '#202028'); put(x + 1, y + 1, '#202028'); put(x + 2, y, '#202028'); }
    else if (op === 'mo') { for (let a = 0; a < s[3]; a++) put(x + a, y, '#202028'); }
    else if (op === 'bl') { put(x, y, '#ff8fa0'); put(x + 1, y, '#ff8fa0'); }
    else if (op === 'px') put(x, y, s[3]);
    else if (op === 'ln') line(s[1], s[2], s[3], s[4], s[5], false);
    else if (op === 'lnc') line(s[1], s[2], s[3], s[4], s[5], true);
  }
  return out;
}

